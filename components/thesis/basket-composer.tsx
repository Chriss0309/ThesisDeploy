export type EditAction = "remove" | "restore" | "reweight" | "step";

type Tone = NonNullable<VariantProps<typeof badgeVariants>["tone"]>;

const RISK_TONE: Record<ComposerPayload["thesis"]["riskProfile"], Tone> = {
  conservative: "neutral",
  moderate: "neutral",
  aggressive: "warning",
  speculative: "warning",
};

const DROP_LABEL: Record<ComposerPayload["dropped"][number]["status"], string> = {
  not_found: "Not found",
  untradeable: "Not a stock",
  currency_mismatch: "Wrong currency",
  no_price: "No price",
  duplicate: "Duplicate",
  invalid: "Invalid",
};

const BAR_COLORS = ["bg-chart-1", "bg-chart-2", "bg-chart-3", "bg-chart-4", "bg-chart-5"];

const initialLines = (payload: ComposerPayload): EditableLine[] =>
  payload.lines.map((line) => ({
    symbol: line.symbol,
    price: line.price,
    weight: line.targetWeight,
    units: line.units,
    removed: false,
  }));

function SourceLine({ payload }: { payload: ComposerPayload }) {
  const { thesis, pricing } = payload;
  const generatedBy =
    thesis.source === "sample"
      ? "Sample basket: live generation isn't available here, so this preset shows committed sample output"
      : thesis.source === "cached"
        ? `Cached ${thesis.model} result from ${formatTimestamp(thesis.generatedAt)}`
        : `Generated by ${thesis.model}${thesis.latencyMs != null ? ` in ${(thesis.latencyMs / 1000).toFixed(1)}s` : ""}`;
  const prices =
    pricing.source === "demo"
      ? `fictional demo prices as of ${formatTimestamp(pricing.asOf)}`
      : `SnapTrade quotes for ${payload.account.name} (may be delayed)`;
  const market = pricing.marketOpen
    ? `${pricing.market} open: buys priced at the ask`
    : `${pricing.market} closed: priced at the last trade`;
  return (
    <p className="text-xs text-muted-foreground">
      {generatedBy}. Prices: {prices}. {market}.
    </p>
  );
}

function CapitalSummary({
  payload,
  lines,
  allocation,
}: {
  payload: ComposerPayload;
  lines: EditableLine[];
  allocation: ReturnType<typeof summarize>;
}) {
  const { currency, budget } = payload;
  const orders = allocation.lines.filter((line) => line.units > 0).length;
  const active = lines.filter((line) => !line.removed);
  const bought = allocation.lines.filter((line) => line.cost > 0);
  return (
    <section aria-label="Capital" className="flex flex-col gap-3 rounded-md bg-surface-sunken p-4">
      <p className="eyebrow text-muted-foreground">► Capital · {currency}</p>
      <p className="font-display text-2xl font-semibold tabular-nums" aria-live="polite">
        {formatMoney(allocation.invested, currency)} deployed · {formatMoney(allocation.unallocated, currency)}{" "}
        unallocated
      </p>
      <p className="text-xs text-muted-foreground">
        Of a {formatMoney(budget, currency)} budget, across {orders} whole-share {orders === 1 ? "order" : "orders"}.
        Market orders can fill above the quote, so {formatPercent(payload.slippageBuffer)} (
        {formatMoney(budget * payload.slippageBuffer, currency)}) is held back when sizing.
      </p>
      <div
        role="img"
        aria-label={`Budget used: ${bought
          .map((line) => `${line.symbol} ${formatMoney(line.cost, currency)}`)
          .join(", ")}; unallocated ${formatMoney(allocation.unallocated, currency)}`}
        className="flex h-3 w-full gap-px overflow-hidden rounded-xs bg-chart-track"
      >
        {bought.map((line, index) => (
          <div
            key={line.symbol}
            className={BAR_COLORS[index % BAR_COLORS.length]}
            style={{ width: `${Math.max(0, Math.min(1, line.cost / budget)) * 100}%` }}
          />
        ))}
      </div>
      {active.length > 0 && active.every((line) => line.weight === 0) && (
        <p className="text-xs text-muted-foreground">
          Every name here is already held at or above its target. Raise a weight, or switch overlap handling to Ignore.
        </p>
      )}
    </section>
  );
}

function Stepper({
  symbol,
  units,
  addBlockedReason,
  onStep,
}: {
  symbol: string;
  units: number;
  /** Why "+" is disabled; null when one more share fits under the spend cap. */
  addBlockedReason: string | null;
  onStep: (delta: number) => void;
}) {
  return (
    <div role="group" aria-label={`Shares of ${symbol}`} className="inline-flex h-8 items-stretch overflow-hidden rounded-md border border-input bg-card">
      <Button
        variant="ghost"
        size="icon-sm"
        className="h-full rounded-none"
        aria-label={`One fewer share of ${symbol}`}
        disabled={units === 0}
        onClick={() => onStep(-1)}
      >
        <Minus />
      </Button>
      <span
        className="flex w-12 items-center justify-center border-x border-input font-mono text-sm tabular-nums"
        aria-live="polite"
      >
        {units}
      </span>
      <Tooltip content={addBlockedReason} disabled={addBlockedReason == null}>
        <Button
          variant="ghost"
          size="icon-sm"
          className="h-full rounded-none data-disabled:cursor-not-allowed data-disabled:opacity-50"
          aria-label={
            addBlockedReason
              ? `One more share of ${symbol} (unavailable: ${addBlockedReason.charAt(0).toLowerCase()}${addBlockedReason.slice(1)})`
              : `One more share of ${symbol}`
          }
          disabled={addBlockedReason != null}
          focusableWhenDisabled
          onClick={() => onStep(1)}
        >
          <Plus />
        </Button>
      </Tooltip>
    </div>
  );
}

function LineRow({
  line,
  editable,
  allocated,
  payload,
  spendCap,
  cashLeft,
  canAdd,
  onWeight,
  onStep,
  onRemove,
}: {
  line: ComposerLine;
  editable: EditableLine;
  allocated: AllocatedLine | undefined;
  payload: ComposerPayload;
  spendCap: number;
  /** Cash left under the spend cap for the whole basket. */
  cashLeft: number;
  canAdd: boolean;
  onWeight: (weight: number) => void;
  onStep: (delta: number) => void;
  onRemove: () => void;
}) {
  const { currency } = payload;
  const weightPct = Math.round(editable.weight * 1000) / 10;
  const slice = editable.weight * spendCap;
  const tooPricey = editable.units === 0 && editable.weight > 0 && line.price > slice;
  const addBlockedReason = canAdd
    ? null
    : `Needs ${formatMoney(line.price, currency)}, ${formatMoney(Math.max(0, cashLeft), currency)} left after the slippage reserve`;
  return (
    <li className="flex flex-col gap-3 border-b py-4 last:border-0">
      <div className="flex items-start justify-between gap-4">
        <div className="flex min-w-0 flex-1 flex-col gap-1">
          <span className="flex flex-wrap items-baseline gap-x-2">
            <span className="font-mono text-sm font-medium">{line.symbol}</span>
            <span className="text-sm text-muted-foreground">{line.companyName}</span>
            {line.exchange && <span className="eyebrow text-muted-foreground">{line.exchange}</span>}
          </span>
          <p className="max-w-prose text-sm text-pretty">{line.rationale}</p>
        </div>
        <div className="flex shrink-0 flex-col items-end gap-0.5">
          <span className="text-sm font-medium tabular-nums">{formatMoney(line.price, currency)}</span>
          <span className="eyebrow text-muted-foreground">{line.priceBasis === "ask" ? "Ask" : "Last trade"}</span>
        </div>
      </div>

      <OverlapBadge line={line} currency={currency} budget={payload.budget} />

      <div className="flex flex-col gap-3 sm:flex-row sm:items-center sm:gap-5">
        <div className="flex items-center gap-3">
          <span className="eyebrow text-muted-foreground">Weight</span>
          <Slider
            aria-label={`Target weight of ${line.symbol}`}
            className="flex-1 sm:w-30 sm:flex-none"
            min={0}
            max={100}
            step={1}
            largeStep={5}
            value={weightPct}
            onValueChange={(value) => onWeight(value / 100)}
          />
          <span className="flex flex-col items-end">
            <span className="text-sm font-medium tabular-nums">{weightPct.toFixed(1)}%</span>
            {allocated && allocated.units > 0 && (
              <span className="text-xs text-muted-foreground tabular-nums">
                actual {formatPercent(allocated.achievedWeight)}
              </span>
            )}
          </span>
        </div>
        <div className="flex items-center justify-between gap-3 sm:ml-auto sm:justify-end">
          <Stepper symbol={line.symbol} units={editable.units} addBlockedReason={addBlockedReason} onStep={onStep} />
          <span className="text-sm font-medium tabular-nums">{formatMoney(allocated?.cost ?? 0, currency)}</span>
          <Button variant="destructive" size="icon-sm" aria-label={`Remove ${line.symbol}`} onClick={onRemove}>
            <Trash2 />
          </Button>
        </div>
      </div>
      {tooPricey && (
        <p className="text-xs text-muted-foreground">
          One share ({formatMoney(line.price, currency)}) costs more than this {weightPct.toFixed(1)}% slice (
          {formatMoney(slice, currency)}), so it gets none. Raise its weight to include it.
        </p>
      )}
    </li>
  );
}

/**
 * Edits recompute in the browser with the same whole-share solver the server
 * used. Changing a weight, removing, or restoring re-solves every line; the
 * stepper overrides one line's shares.
 */
export function BasketComposer({
  payload,
  onEdit,
  preflightEndpoint,
}: {
  payload: ComposerPayload;
  onEdit?: (action: EditAction, symbol: string) => void;
  /** Where pre-flight runs; without it the composer is read-only for execution. */
  preflightEndpoint?: string;
}) {
  const [lines, setLines] = useState(() => initialLines(payload));
  const [preflight, setPreflight] = useState<PreflightRequest | null>(null);
  const [dialogOpen, setDialogOpen] = useState(false);
  const [savedBasket, setSavedBasket] = useState<string | null>(null);
  const settings: BasketSettings = { budget: payload.budget, slippageBuffer: payload.slippageBuffer };
  const allocation = useMemo(
    () => summarize(lines, { budget: payload.budget, slippageBuffer: payload.slippageBuffer }),
    [lines, payload.budget, payload.slippageBuffer],
  );
  const allocated = new Map(allocation.lines.map((line) => [line.symbol, line]));
  const removed = payload.lines.filter((line) => lines.find((l) => l.symbol === line.symbol)?.removed);
  const edited = lines.some((line, i) => line.removed || line.units !== payload.lines[i].units || line.weight !== payload.lines[i].targetWeight);
  const { thesis } = payload;
  const orders = allocation.lines.filter((line) => line.units > 0).length;
  const canPreflight = Boolean(preflightEndpoint) && orders > 0;

  const openPreflight = () => {
    setPreflight({
      thesisId: thesis.id,
      accountId: payload.account.id,
      currency: payload.currency,
      budget: payload.budget,
      thesis: { title: thesis.title, summary: thesis.summary, riskProfile: thesis.riskProfile },
      lines: payload.lines.flatMap((line, i) =>
        lines[i].removed
          ? []
          : [
              {
                symbol: line.symbol,
                companyName: line.companyName,
                universalSymbolId: line.universalSymbolId,
                targetWeight: lines[i].weight,
                units: lines[i].units,
              },
            ],
      ),
    });
    setDialogOpen(true);
  };

  return (
    <Card>
      <CardHeader className="gap-2">
        <div className="flex flex-wrap items-start justify-between gap-x-4 gap-y-2">
          <div className="flex flex-col gap-1">
            <p className="eyebrow text-muted-foreground">► Thesis · Basket Composer</p>
            <CardTitle className="font-display text-xl font-semibold">{thesis.title}</CardTitle>
          </div>
          <div className="flex flex-wrap gap-1">
            <Badge tone={RISK_TONE[thesis.riskProfile]}>{thesis.riskProfile} risk</Badge>
            {payload.account.isPaper && <Badge tone="info">Paper</Badge>}
            <Badge>
              {payload.currency} · {payload.account.name}
            </Badge>
          </div>
        </div>
        <CardDescription className="max-w-prose text-pretty text-foreground">{thesis.summary}</CardDescription>
        <SourceLine payload={payload} />
      </CardHeader>

      <CardContent className="flex flex-col gap-5">
        {payload.notices.map((notice) => (
          <p
            key={notice}
            role="status"
            className="rounded-md border border-warning-border bg-warning-subtle px-3 py-2.5 text-xs text-warning-subtle-foreground"
          >
            {notice}
          </p>
        ))}
        <CapitalSummary payload={payload} lines={lines} allocation={allocation} />

        {payload.lines.length === 0 ? (
          <p className="text-sm text-muted-foreground">
            None of the proposed tickers could be bought in {payload.currency} on this account. See why below, or try
            another account or currency.
          </p>
        ) : (
          <ul aria-label="Basket constituents">
            {payload.lines.map((line, i) =>
              lines[i].removed ? null : (
                <LineRow
                  key={line.symbol}
                  line={line}
                  editable={lines[i]}
                  allocated={allocated.get(line.symbol)}
                  payload={payload}
                  spendCap={allocation.spendCap}
                  cashLeft={allocation.spendCap - allocation.invested}
                  canAdd={canAddShare(lines, line.symbol, settings)}
                  onWeight={(weight) => {
                    setLines((current) => setWeight(current, line.symbol, weight, settings));
                    onEdit?.("reweight", line.symbol);
                  }}
                  onStep={(delta) => {
                    setLines((current) => stepUnits(current, line.symbol, delta, settings));
                    onEdit?.("step", line.symbol);
                  }}
                  onRemove={() => {
                    setLines((current) => removeLine(current, line.symbol, settings));
                    onEdit?.("remove", line.symbol);
                  }}
                />
              ),
            )}
          </ul>
        )}

        {removed.length > 0 && (
          <section aria-label="Removed by you" className="flex flex-col gap-2">
            <h3 className="eyebrow text-muted-foreground">► Removed by you</h3>
            <ul className="flex flex-wrap gap-2">
              {removed.map((line) => (
                <li key={line.symbol}>
                  <Button
                    variant="outline"
                    size="xs"
                    onClick={() => {
                      setLines((current) => restoreLine(current, line.symbol, settings));
                      onEdit?.("restore", line.symbol);
                    }}
                  >
                    <Undo2 /> Restore <span className="font-mono">{line.symbol}</span>
                  </Button>
                </li>
              ))}
            </ul>
          </section>
        )}

        {payload.dropped.length > 0 && (
          <section aria-label="Not in the basket" className="flex flex-col gap-2">
            <h3 className="eyebrow text-muted-foreground">
              ► Left out by SnapTrade grounding ({payload.dropped.length})
            </h3>
            <ul className="flex flex-col gap-2 text-xs">
              {payload.dropped.map((drop) => (
                <li key={`${drop.ticker}-${drop.status}`} className="flex flex-wrap items-center gap-2">
                  <span className="font-mono font-medium">{drop.ticker}</span>
                  <Badge tone="negative">{DROP_LABEL[drop.status]}</Badge>
                  <span className="text-muted-foreground">
                    {drop.companyName}: {drop.detail}
                  </span>
                </li>
              ))}
            </ul>
          </section>
        )}

        {payload.excluded.length > 0 && (
          <section aria-label="Considered and excluded" className="flex flex-col gap-2">
            <h3 className="eyebrow text-muted-foreground">► Considered and excluded by Claude</h3>
            <ul className="flex flex-col gap-1.5 text-xs text-muted-foreground">
              {payload.excluded.map((entry) => (
                <li key={entry.ticker}>
                  <span className="font-mono font-medium text-foreground">{entry.ticker}</span>: {entry.reason}
                </li>
              ))}
            </ul>
          </section>
        )}
      </CardContent>

      <CardFooter className="flex-wrap justify-between gap-3">
        <p className="flex items-center gap-2 text-xs text-muted-foreground">
          {savedBasket ? (
            <>
              <Mark kind="success" size="inline" />
              Saved as a Paper basket.{" "}
              <Link href={savedBasket} className="font-medium text-brand underline-offset-4 hover:underline">
                View saved basket
              </Link>
            </>
          ) : (
            "Nothing is ordered until you confirm in pre-flight."
          )}
        </p>
        <div className="flex gap-2">
          <Button variant="outline" size="sm" disabled={!edited} onClick={() => setLines(initialLines(payload))}>
            Reset edits
          </Button>
          <Button variant="brand" size="sm" disabled={!canPreflight} onClick={openPreflight}>
            Continue to pre-flight
          </Button>
        </div>
      </CardFooter>
      {preflightEndpoint && (
        <PreflightDialog
          open={dialogOpen}
          onOpenChange={setDialogOpen}
          endpoint={preflightEndpoint}
          request={preflight}
          onExecuted={setSavedBasket}
        />
      )}
    </Card>
  );
}
