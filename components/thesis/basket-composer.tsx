"use client";

import { Minus, Plus, Trash2, Undo2 } from "lucide-react";
import { useMemo, useState } from "react";

import { formatMoney, formatPercent, formatTimestamp } from "@/components/portfolio/format";
import { OverlapBadge } from "@/components/thesis/overlap-badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardFooter, CardHeader } from "@/components/ui/card";
import { Pill } from "@/components/ui/pill";
import type { AllocatedLine } from "@/lib/solver";
import {
  removeLine,
  restoreLine,
  setWeight,
  stepUnits,
  summarize,
  type BasketSettings,
  type EditableLine,
} from "@/lib/thesis/composer-state";
import type { ComposerLine, ComposerPayload } from "@/lib/thesis/types";
import { cn } from "@/lib/utils";

export type EditAction = "remove" | "restore" | "reweight" | "step";

const RISK_TONE = { conservative: "good", moderate: "info", aggressive: "warn", speculative: "bad" } as const;

const DROP_LABEL: Record<ComposerPayload["dropped"][number]["status"], string> = {
  not_found: "Not found",
  untradeable: "Not a stock",
  currency_mismatch: "Wrong currency",
  no_price: "No price",
  duplicate: "Duplicate",
  invalid: "Invalid",
};

const BAR_COLORS = ["bg-sky-700", "bg-sky-600", "bg-sky-500", "bg-sky-400", "bg-sky-300", "bg-indigo-400", "bg-indigo-300", "bg-indigo-200"];

const initialLines = (payload: ComposerPayload): EditableLine[] =>
  payload.lines.map((line) => ({
    symbol: line.symbol,
    price: line.price,
    weight: line.targetWeight,
    units: line.units,
    removed: false,
  }));

function SourceLine({ payload }: { payload: ComposerPayload }) {
  const { thesis, pricing } = payload;
  const generatedBy =
    thesis.source === "sample"
      ? "Sample basket: live generation isn't available here, so this preset shows committed sample output"
      : thesis.source === "cached"
        ? `Cached ${thesis.model} result from ${formatTimestamp(thesis.generatedAt)}`
        : `Generated by ${thesis.model}${thesis.latencyMs != null ? ` in ${(thesis.latencyMs / 1000).toFixed(1)}s` : ""}`;
  const prices =
    pricing.source === "demo"
      ? `fictional demo prices as of ${formatTimestamp(pricing.asOf)}`
      : `SnapTrade quotes for ${payload.account.name} (may be delayed)`;
  const market = pricing.marketOpen
    ? `${pricing.market} open: buys priced at the ask`
    : `${pricing.market} closed: priced at the last trade`;
  return (
    <p className="text-xs text-muted-foreground">
      {generatedBy}. Prices: {prices}. {market}.
    </p>
  );
}

function CapitalSummary({
  payload,
  lines,
  allocation,
}: {
  payload: ComposerPayload;
  lines: EditableLine[];
  allocation: ReturnType<typeof summarize>;
}) {
  const { currency, budget } = payload;
  const orders = allocation.lines.filter((line) => line.units > 0).length;
  const over = allocation.overSpendCap;
  const active = lines.filter((line) => !line.removed);
  return (
    <div className="flex flex-col gap-2 rounded-lg border p-3">
      <p className="text-sm" aria-live="polite">
        Deploying <strong className="tabular-nums">{formatMoney(allocation.invested, currency)}</strong> of{" "}
        <span className="tabular-nums">{formatMoney(budget, currency)}</span> across {orders} whole-share{" "}
        {orders === 1 ? "order" : "orders"};{" "}
        <strong className={cn("tabular-nums", allocation.unallocated < 0 && "text-destructive")}>
          {formatMoney(allocation.unallocated, currency)}
        </strong>{" "}
        {allocation.unallocated < 0 ? "over budget" : "stays in cash"}.
      </p>
      <div className="flex h-2.5 w-full overflow-hidden rounded-full bg-muted" aria-hidden>
        {allocation.lines.map((line, index) => (
          <div
            key={line.symbol}
            className={BAR_COLORS[index % BAR_COLORS.length]}
            style={{ width: `${Math.max(0, Math.min(1, line.cost / budget)) * 100}%` }}
          />
        ))}
      </div>
      <p className="text-xs text-muted-foreground">
        Market orders can fill above the quote, so {formatPercent(payload.slippageBuffer)} of the budget (
        {formatMoney(budget * payload.slippageBuffer, currency)}) is held back when sizing.
        {active.length > 0 && active.every((line) => line.weight === 0) &&
          " Every name here is already held at or above its target; raise a weight or switch overlap handling to Ignore."}
      </p>
      {over && (
        <p role="alert" className="text-xs text-destructive">
          Manual share counts exceed the spend cap of {formatMoney(allocation.spendCap, currency)}. Remove shares
          before continuing.
        </p>
      )}
    </div>
  );
}

function LineRow({
  line,
  editable,
  allocated,
  payload,
  spendCap,
  onWeight,
  onStep,
  onRemove,
}: {
  line: ComposerLine;
  editable: EditableLine;
  allocated: AllocatedLine | undefined;
  payload: ComposerPayload;
  spendCap: number;
  onWeight: (weight: number) => void;
  onStep: (delta: number) => void;
  onRemove: () => void;
}) {
  const { currency } = payload;
  const weightPct = Math.round(editable.weight * 1000) / 10;
  const slice = editable.weight * spendCap;
  const tooPricey = editable.units === 0 && editable.weight > 0 && line.price > slice;
  const inputId = `weight-${line.symbol}`;
  return (
    <li className="flex flex-col gap-3 border-b py-4 last:border-0">
      <div className="grid grid-cols-[1fr_auto] items-start gap-x-4">
        <div className="flex min-w-0 flex-col">
          <span className="flex flex-wrap items-baseline gap-x-2">
            <span className="font-semibold">{line.symbol}</span>
            <span className="text-sm text-muted-foreground">
              {line.companyName}
              {line.exchange ? ` · ${line.exchange}` : ""}
            </span>
          </span>
          <p className="mt-1 text-sm text-pretty">{line.rationale}</p>
        </div>
        <div className="text-right text-sm tabular-nums">
          <div className="font-medium">{formatMoney(line.price, currency)}</div>
          <div className="text-xs text-muted-foreground">{line.priceBasis === "ask" ? "ask" : "last trade"}</div>
        </div>
      </div>

      <OverlapBadge line={line} currency={currency} budget={payload.budget} />

      <div className="grid items-center gap-x-6 gap-y-3 sm:grid-cols-[1fr_auto_auto]">
        <div className="flex flex-col gap-1">
          <label htmlFor={inputId} className="flex justify-between text-xs text-muted-foreground">
            <span>Target weight</span>
            <span className="tabular-nums">
              <span className="font-medium text-foreground">{weightPct.toFixed(1)}%</span>
              {allocated && allocated.units > 0 && ` · actual ${formatPercent(allocated.achievedWeight)}`}
            </span>
          </label>
          <input
            id={inputId}
            type="range"
            min={0}
            max={100}
            step={1}
            value={weightPct}
            onChange={(event) => onWeight(Number(event.target.value) / 100)}
            className="w-full accent-sky-700"
          />
        </div>
        <div className="flex items-center gap-2">
          <span className="text-xs text-muted-foreground">Shares</span>
          <div className="flex items-center rounded-lg border">
            <Button
              variant="ghost"
              size="icon-sm"
              aria-label={`One fewer share of ${line.symbol}`}
              disabled={editable.units === 0}
              onClick={() => onStep(-1)}
            >
              <Minus />
            </Button>
            <span className="w-10 text-center text-sm font-medium tabular-nums" aria-live="polite">
              {editable.units}
            </span>
            <Button variant="ghost" size="icon-sm" aria-label={`One more share of ${line.symbol}`} onClick={() => onStep(1)}>
              <Plus />
            </Button>
          </div>
        </div>
        <div className="flex items-center justify-between gap-3 sm:justify-end">
          <span className="text-sm font-medium tabular-nums">{formatMoney(allocated?.cost ?? 0, currency)}</span>
          <Button variant="ghost" size="icon-sm" aria-label={`Remove ${line.symbol}`} onClick={onRemove}>
            <Trash2 className="text-muted-foreground" />
          </Button>
        </div>
      </div>
      {tooPricey && (
        <p className="text-xs text-amber-800">
          One share ({formatMoney(line.price, currency)}) costs more than this {weightPct.toFixed(1)}% slice (
          {formatMoney(slice, currency)}), so it gets none. Raise its weight or add a share manually.
        </p>
      )}
    </li>
  );
}

/**
 * Edits recompute in the browser with the same whole-share solver the server
 * used. Changing a weight, removing, or restoring re-solves every line; the
 * stepper overrides one line's shares.
 */
export function BasketComposer({
  payload,
  onEdit,
}: {
  payload: ComposerPayload;
  onEdit?: (action: EditAction, symbol: string) => void;
}) {
  const [lines, setLines] = useState(() => initialLines(payload));
  const settings: BasketSettings = { budget: payload.budget, slippageBuffer: payload.slippageBuffer };
  const allocation = useMemo(
    () => summarize(lines, { budget: payload.budget, slippageBuffer: payload.slippageBuffer }),
    [lines, payload.budget, payload.slippageBuffer],
  );
  const allocated = new Map(allocation.lines.map((line) => [line.symbol, line]));
  const removed = payload.lines.filter((line) => lines.find((l) => l.symbol === line.symbol)?.removed);
  const edited = lines.some((line, i) => line.removed || line.units !== payload.lines[i].units || line.weight !== payload.lines[i].targetWeight);
  const { thesis } = payload;

  return (
    <Card>
      <CardHeader className="gap-2">
        <div className="flex flex-wrap items-start justify-between gap-2">
          <div className="flex flex-col gap-1">
            <span className="text-xs font-medium tracking-wide text-muted-foreground uppercase">Basket Composer</span>
            <h2 className="text-lg font-semibold tracking-tight">{thesis.title}</h2>
          </div>
          <div className="flex flex-wrap gap-1">
            <Pill tone={RISK_TONE[thesis.riskProfile]}>{thesis.riskProfile} risk</Pill>
            <Pill tone={payload.account.isPaper ? "info" : "neutral"}>
              {payload.currency} · {payload.account.name}
            </Pill>
          </div>
        </div>
        <p className="text-sm text-pretty">{thesis.summary}</p>
        <SourceLine payload={payload} />
      </CardHeader>

      <CardContent className="flex flex-col gap-4">
        {payload.notices.map((notice) => (
          <p key={notice} role="status" className="rounded-md border border-amber-200 bg-amber-50 px-3 py-2 text-xs text-amber-900">
            {notice}
          </p>
        ))}
        <CapitalSummary payload={payload} lines={lines} allocation={allocation} />

        {payload.lines.length === 0 ? (
          <p className="text-sm text-muted-foreground">
            None of the proposed tickers could be bought in {payload.currency} on this account. See why below, or try
            another account or currency.
          </p>
        ) : (
          <ul aria-label="Basket constituents">
            {payload.lines.map((line, i) =>
              lines[i].removed ? null : (
                <LineRow
                  key={line.symbol}
                  line={line}
                  editable={lines[i]}
                  allocated={allocated.get(line.symbol)}
                  payload={payload}
                  spendCap={allocation.spendCap}
                  onWeight={(weight) => {
                    setLines((current) => setWeight(current, line.symbol, weight, settings));
                    onEdit?.("reweight", line.symbol);
                  }}
                  onStep={(delta) => {
                    setLines((current) => stepUnits(current, line.symbol, delta));
                    onEdit?.("step", line.symbol);
                  }}
                  onRemove={() => {
                    setLines((current) => removeLine(current, line.symbol, settings));
                    onEdit?.("remove", line.symbol);
                  }}
                />
              ),
            )}
          </ul>
        )}

        {removed.length > 0 && (
          <section aria-label="Removed by you" className="flex flex-col gap-2">
            <h3 className="text-xs font-medium text-muted-foreground">Removed by you</h3>
            <ul className="flex flex-wrap gap-2">
              {removed.map((line) => (
                <li key={line.symbol}>
                  <Button
                    variant="outline"
                    size="xs"
                    onClick={() => {
                      setLines((current) => restoreLine(current, line.symbol, settings));
                      onEdit?.("restore", line.symbol);
                    }}
                  >
                    <Undo2 /> Restore {line.symbol}
                  </Button>
                </li>
              ))}
            </ul>
          </section>
        )}

        {payload.dropped.length > 0 && (
          <section aria-label="Not in the basket" className="flex flex-col gap-2">
            <h3 className="text-xs font-medium text-muted-foreground">
              Proposed but left out by SnapTrade grounding ({payload.dropped.length})
            </h3>
            <ul className="flex flex-col gap-1.5 text-xs">
              {payload.dropped.map((drop) => (
                <li key={`${drop.ticker}-${drop.status}`} className="flex flex-wrap items-center gap-2">
                  <span className="font-medium">{drop.ticker}</span>
                  <Pill tone="bad">{DROP_LABEL[drop.status]}</Pill>
                  <span className="text-muted-foreground">
                    {drop.companyName}: {drop.detail}
                  </span>
                </li>
              ))}
            </ul>
          </section>
        )}

        {payload.excluded.length > 0 && (
          <section aria-label="Considered and excluded" className="flex flex-col gap-2">
            <h3 className="text-xs font-medium text-muted-foreground">Considered and excluded by Claude</h3>
            <ul className="flex flex-col gap-1 text-xs text-muted-foreground">
              {payload.excluded.map((entry) => (
                <li key={entry.ticker}>
                  <span className="font-medium text-foreground">{entry.ticker}</span>: {entry.reason}
                </li>
              ))}
            </ul>
          </section>
        )}
      </CardContent>

      <CardFooter className="flex flex-wrap items-center justify-between gap-3 border-t py-3">
        <p className="text-xs text-muted-foreground">
          Pre-flight checks and paper or live execution come next. Nothing has been ordered.
        </p>
        <div className="flex gap-2">
          <Button variant="outline" size="sm" disabled={!edited} onClick={() => setLines(initialLines(payload))}>
            Reset edits
          </Button>
          <Button size="sm" disabled>
            Continue to pre-flight
          </Button>
        </div>
      </CardFooter>
    </Card>
  );
}
